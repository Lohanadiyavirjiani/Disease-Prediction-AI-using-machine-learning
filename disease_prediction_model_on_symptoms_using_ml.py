def predict_disease(symptoms):

    input_data = pd.DataFrame(
        [symptoms],
        columns=X.columns
    )

    prediction = best_model.predict(input_data)

    disease = label_encoder.inverse_transform(prediction)[0]

    print("Predicted Disease:", disease)

    return disease

