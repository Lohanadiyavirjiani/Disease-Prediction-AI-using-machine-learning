import os
import warnings
import joblib
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

warnings.filterwarnings("ignore")

from sklearn.preprocessing import LabelEncoder
from sklearn.model_selection import train_test_split

from sklearn.linear_model import LogisticRegression
from sklearn.tree import DecisionTreeClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.neighbors import KNeighborsClassifier

from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    classification_report,
    confusion_matrix
)

print("Libraries imported successfully!")
print("NumPy:", np.__version__)
print("Pandas:", pd.__version__)
print("Seaborn:", sns.__version__)

# ============================================================
# CELL 2: LOAD DATASET
# ============================================================

file_path = "/content/Testing.csv"

df = pd.read_csv(file_path)

print("Dataset loaded successfully!")
print("Shape:", df.shape)
print("\nColumns:")
print(df.columns.tolist())

# ============================================================
# CELL 3: BASIC DATASET CHECK
# ============================================================

print("Dataset Shape:", df.shape)
print("\nFirst 5 rows:")
display(df.head())

print("\nTarget column candidates:")
print(df.columns[-5:].tolist())

# ============================================================
# CELL 4: FIND TARGET COLUMN
# ============================================================

possible_targets = [
    "prognosis",
    "Prognosis",
    "disease",
    "Disease",
    "target",
    "Target"
]

target_column = None

for col in possible_targets:
    if col in df.columns:
        target_column = col
        break

if target_column is None:
    print("Target column automatically nahi mila.")
    print("Available columns:")
    print(df.columns.tolist())
else:
    print("Target column:", target_column)
    print("\nNumber of diseases:", df[target_column].nunique())
    print("\nDisease classes:")
    print(df[target_column].unique())

# ============================================================
# CELL 5: PREPARE FEATURES AND TARGET
# ============================================================

X = df.drop(columns=[target_column])
y = df[target_column]

print("Features shape:", X.shape)
print("Target shape:", y.shape)

print("\nNumber of features:", X.shape[1])
print("Number of diseases:", y.nunique())

# ============================================================
# CELL 6: ENCODE TARGET
# ============================================================

label_encoder = LabelEncoder()

y_encoded = label_encoder.fit_transform(y)

print("Disease encoding completed!")
print("Total classes:", len(label_encoder.classes_))

print("\nDisease mapping:")
for number, disease in enumerate(label_encoder.classes_):
    print(number, "=", disease)

# ============================================================
# CELL 7: TRAIN TEST SPLIT
# ============================================================

X_train, X_test, y_train, y_test = train_test_split(
    X,
    y_encoded,
    test_size=0.20,
    random_state=42
)

print("Training data:", X_train.shape)
print("Testing data:", X_test.shape)

from xgboost import XGBClassifier

# ============================================================
# CELL 8: TRAIN ML MODELS
# ============================================================

models = {
    "Logistic Regression": LogisticRegression(
        max_iter=2000,
        random_state=42
    ),

    "Decision Tree": DecisionTreeClassifier(
        random_state=42
    ),

    "Random Forest": RandomForestClassifier(
        n_estimators=200,
        random_state=42
    ),

    "XGBoost": XGBClassifier(
        n_estimators=200,
        max_depth=6,
        learning_rate=0.1,
        random_state=42,
        eval_metric="mlogloss",
        objective="multi:softmax"
    )
}

results = []

for name, model in models.items():
    # Special handling for XGBoost due to its strict label requirements
    if name == "XGBoost":
        # Create a LabelEncoder that is ONLY aware of the classes present in the training data for XGBoost
        xgb_train_specific_encoder = LabelEncoder()
        y_train_for_xgb = xgb_train_specific_encoder.fit_transform(y_train)
        # y_train_for_xgb now has contiguous labels from 0 to (num_unique_classes_in_y_train - 1)

        # For the test set, we need to ensure that its labels are also mapped according to
        # the classes seen during training. Handle potential unseen labels in y_test.
        known_classes_in_train = xgb_train_specific_encoder.classes_

        # Create a boolean mask for y_test where labels are known from training
        mask_known_labels_in_test = np.isin(y_test, known_classes_in_train)

        # Filter X_test and y_test using this mask for XGBoost specific evaluation
        X_test_xgb_filtered = X_test[mask_known_labels_in_test]
        y_test_xgb_filtered = y_test[mask_known_labels_in_test]

        if X_test_xgb_filtered.empty:
            # If no test samples have labels known from training, metrics are 0
            accuracy = 0.0
            precision = 0.0
            recall = 0.0
            f1 = 0.0
        else:
            # Transform the filtered y_test labels using the encoder fitted on y_train
            # This will only contain labels that were seen in the training set
            y_test_for_xgb = xgb_train_specific_encoder.transform(y_test_xgb_filtered)

            model.fit(X_train, y_train_for_xgb)
            y_pred = model.predict(X_test_xgb_filtered)

            accuracy = accuracy_score(y_test_for_xgb, y_pred)
            precision = precision_score(
                y_test_for_xgb, y_pred, average="weighted", zero_division=0
            )
            recall = recall_score(
                y_test_for_xgb, y_pred, average="weighted", zero_division=0
            )
            f1 = f1_score(
                y_test_for_xgb, y_pred, average="weighted", zero_division=0
            )
    else:
        model.fit(X_train, y_train)
        y_pred = model.predict(X_test)
        accuracy = accuracy_score(y_test, y_pred)
        precision = precision_score(
            y_test, y_pred, average="weighted", zero_division=0
        )
        recall = recall_score(
            y_test, y_pred, average="weighted", zero_division=0
        )
        f1 = f1_score(
            y_test, y_pred, average="weighted", zero_division=0
        )

    results.append({
        "Model": name,
        "Accuracy": accuracy,
        "Precision": precision,
        "Recall": recall,
        "F1 Score": f1
    })

results_df = pd.DataFrame(results)

print("Model training completed!")
display(results_df.sort_values("F1 Score", ascending=False))

# ============================================================
# CELL 9: SELECT BEST MODEL
# ============================================================

best_model_name = results_df.loc[
    results_df["F1 Score"].idxmax(), "Model"
]

best_model = models[best_model_name]

print("Best Model:", best_model_name)
print(
    "Best F1 Score:",
    round(
        results_df.loc[
            results_df["Model"] == best_model_name,
            "F1 Score"
        ].iloc[0],
        4
    )
)

# ============================================================
# CELL 10: CONFUSION MATRIX
# ============================================================

best_predictions = best_model.predict(X_test)

cm = confusion_matrix(y_test, best_predictions)

plt.figure(figsize=(12, 9))
sns.heatmap(cm, cmap="Blues")
plt.title(f"Confusion Matrix - {best_model_name}")
plt.xlabel("Predicted")
plt.ylabel("Actual")
plt.show()

# ============================================================
# CELL 11: CLASSIFICATION REPORT
# ============================================================

print(f"Classification Report - {best_model_name}\n")

# Get unique labels present in y_test and best_predictions
unique_labels_in_report = np.unique(np.concatenate((y_test, best_predictions)))

# Filter target names to include only those corresponding to the unique labels
report_target_names = [
    label_encoder.classes_[i] for i in unique_labels_in_report
]

print(
    classification_report(
        y_test,
        best_predictions,
        labels=unique_labels_in_report, # Explicitly specify the labels that appear in y_test/best_predictions
        target_names=report_target_names, # Use filtered target names
        zero_division=0
    )
)

